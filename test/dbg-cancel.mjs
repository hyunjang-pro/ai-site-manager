import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright';
const DIST = path.resolve('dist');
const MIME = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript', '.css': 'text/css', '.png': 'image/png', '.jpg': 'image/jpeg', '.svg': 'image/svg+xml', '.json': 'application/json' };
const server = http.createServer((req, res) => {
  const p = decodeURIComponent((req.url || '/').split('?')[0]);
  let file = path.join(DIST, p === '/' ? 'index.html' : p);
  if (!fs.existsSync(file) || fs.statSync(file).isDirectory()) file = path.join(DIST, 'index.html');
  res.writeHead(200, { 'Content-Type': MIME[path.extname(file)] || 'application/octet-stream' });
  fs.createReadStream(file).pipe(res);
});
await new Promise((r) => server.listen(4192, '127.0.0.1', r));
const browser = await chromium.launch({ args: ['--no-sandbox'] });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, locale: 'ko-KR' });
const page = await context.newPage();
page.on('pageerror', (e) => console.log('PAGEERROR', e.message));
page.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE', m.text()); });
await page.goto('http://127.0.0.1:4192/', { waitUntil: 'networkidle' });
for (const d of ['3', '8', '5', '5']) await page.getByLabel(`${d} 번`).click();
await page.getByText('오늘 장부').waitFor();
await page.getByText('안동 풍산읍 15평 상가 원상복구 철거').first().click();
await page.locator('nav[aria-label="현장 단계"] button').nth(2).click();
await page.waitForTimeout(500);
const price = async () => (await page.locator('main').innerText()).match(/견적\s*([\d,]+)만원/)?.[1];
console.log('before', await price(), 'protect in text?', (await page.locator('main').innerText()).includes('보양'));
await page.getByLabel('현장 변동 내용').fill('사다리차 취소, 보양 제외');
await page.waitForTimeout(500);
const t = await page.locator('main').innerText();
console.log('warn box:', t.split('\n').filter((l) => l.includes('빼기로')).join(' | '));
await page.locator('button[data-can-apply]').first().click();
await page.waitForTimeout(1200);
console.log('after', await price());
const t2 = await page.locator('body').innerText();
console.log('toast', t2.split('\n').filter((l) => l.includes('뺐') || l.includes('찾지') || l.includes('빼')).join(' | '));
const state = await page.evaluate(() => JSON.parse(localStorage.getItem('aiSiteManager.v1') || '{}'));
console.log('survey', JSON.stringify(state.cases?.[0]?.survey));
await browser.close();
server.close();
