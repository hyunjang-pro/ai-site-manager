import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright';

const DIST = path.resolve('dist');
const OUT = '/workspace/.tmp/smoke';
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
const MIME = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json' };
const server = http.createServer((req, res) => {
  let f = path.join(DIST, decodeURIComponent((req.url || '/').split('?')[0]) === '/' ? 'index.html' : decodeURIComponent((req.url || '/').split('?')[0]));
  if (!fs.existsSync(f) || fs.statSync(f).isDirectory()) f = path.join(DIST, 'index.html');
  res.writeHead(200, { 'Content-Type': MIME[path.extname(f)] || 'application/octet-stream' });
  fs.createReadStream(f).pipe(res);
});
await new Promise((r) => server.listen(4174, '127.0.0.1', r));
const browser = await chromium.launch({ args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, locale: 'ko-KR', deviceScaleFactor: 1, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const errors = [];
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
page.on('pageerror', (e) => errors.push(`pageerror: ${e.message}`));
await page.goto('http://127.0.0.1:4174/', { waitUntil: 'networkidle' });
await page.screenshot({ path: `${OUT}/00-lock.png` });
for (const d of ['3', '8', '8', '5']) await page.getByLabel(`${d} 번`).click();
await page.getByText('오늘 장부').waitFor({ timeout: 8000 });
await page.waitForTimeout(400);
await page.screenshot({ path: `${OUT}/01-home.png` });
await page.getByText('관공서 일감', { exact: false }).first().click();
await page.waitForTimeout(500);
await page.screenshot({ path: `${OUT}/02-bids.png` });
console.log('bids text:', (await page.locator('main').innerText()).slice(0, 300).replace(/\n/g, ' | '));
const cards = page.locator('main button').filter({ hasText: '추정가격' });
console.log('cards', await cards.count());
if (await cards.count()) {
  await cards.first().click();
  await page.waitForTimeout(400);
  await page.screenshot({ path: `${OUT}/03-bid-detail.png` });
  console.log('detail ok', await page.getByText('투찰가·남는 돈 미리보기').count());
  await page.getByLabel('닫기').click();
}
await page.getByLabel('장부로 돌아가기').click();
await page.getByText('안동 용상동 주방 3.2m 싱크대 교체').click();
await page.getByText('2026 최신 시세 3자 검증').waitFor({ timeout: 6000 });
await page.waitForTimeout(300);
await page.screenshot({ path: `${OUT}/04-estimate-top.png` });
await page.getByText('2026 최신 시세 3자 검증').scrollIntoViewIfNeeded();
await page.waitForTimeout(300);
await page.screenshot({ path: `${OUT}/05-verify.png` });
await page.getByLabel('장부로 돌아가기').click();
await page.getByRole('button', { name: /새 현장 만들기/ }).click();
await page.waitForTimeout(400);
await page.screenshot({ path: `${OUT}/06-newcase.png` });
console.log('newcase modal', await page.getByText('숨고·카톡·메모를 그대로 넣으세요').count());
await page.getByLabel('현장 요청 내용').fill('폐기물 2톤만 치워주세요');
await page.getByRole('button', { name: '자동으로 분류' }).click();
await page.getByText('자동으로 잡았습니다').waitFor({ timeout: 8000 });
await page.waitForTimeout(300);
await page.screenshot({ path: `${OUT}/07-classified.png` });
console.log('result', (await page.locator('main, [role=dialog]').first().innerText()).slice(0, 200).replace(/\n/g, ' | '));
await page.getByRole('button', { name: /이 내용으로 현장 만들기/ }).click();
await page.waitForTimeout(600);
await page.screenshot({ path: `${OUT}/08-created.png` });
const body = await page.locator('body').innerText();
console.log('created includes 폐기물', body.includes('폐기물'), 'title:', (await page.locator('header').innerText()).replace(/\n/g, ' '));
const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
console.log('overflow', overflow, 'errors', errors.slice(0, 5));
await browser.close();
server.close();
