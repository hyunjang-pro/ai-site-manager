import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright';
const DIST = path.resolve('dist');
const MIME = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript', '.css': 'text/css', '.png': 'image/png', '.jpg': 'image/jpeg', '.svg': 'image/svg+xml', '.json': 'application/json' };
const server = http.createServer((req, res) => {
  const p = decodeURIComponent((req.url || '/').split('?')[0]);
  let file = path.join(DIST, p === '/' ? 'index.html' : p);
  if (!fs.existsSync(file) || fs.statSync(file).isDirectory()) file = path.join(DIST, 'index.html');
  res.writeHead(200, { 'Content-Type': MIME[path.extname(file)] || 'application/octet-stream' });
  fs.createReadStream(file).pipe(res);
});
await new Promise((r) => server.listen(4196, '127.0.0.1', r));
const browser = await chromium.launch({ args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, locale: 'ko-KR', deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
page.on('pageerror', (e) => console.log('PAGEERROR', e.message));
await page.goto('http://127.0.0.1:4196/', { waitUntil: 'networkidle' });
for (const d of ['3', '8', '5', '5']) await page.getByLabel(`${d} 번`).click();
await page.getByText('오늘 장부').waitFor();
await page.getByText('관공서 일감').first().click();
await page.waitForTimeout(800);
const card = page.locator('main button').filter({ hasText: /추정가격|예상 투찰가|낙찰하한/ }).first();
if (await card.count()) await card.click();
await page.waitForTimeout(600);
const imp = page.getByRole('button', { name: /내 장부로 가져오기/ }).first();
if (await imp.count()) await imp.click();
await page.waitForTimeout(1500);
await page.locator('nav[aria-label="현장 단계"] button').nth(1).click();
await page.waitForTimeout(700);
await page.evaluate(() => window.scrollTo(0, 520));
await page.waitForTimeout(300);
await page.screenshot({ path: 'screenshots/final-390-bid-estimate.png' });
const t = await page.locator('main').innerText();
console.log(t.split('\n').slice(0, 24).join(' | '));
await browser.close();
server.close();
