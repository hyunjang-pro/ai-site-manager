import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright';
const DIST = path.resolve('dist');
const MIME = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript', '.css': 'text/css', '.png': 'image/png', '.jpg': 'image/jpeg', '.svg': 'image/svg+xml', '.json': 'application/json' };
const server = http.createServer((req, res) => {
  const p = decodeURIComponent((req.url || '/').split('?')[0]);
  let file = path.join(DIST, p === '/' ? 'index.html' : p);
  if (!fs.existsSync(file) || fs.statSync(file).isDirectory()) file = path.join(DIST, 'index.html');
  res.writeHead(200, { 'Content-Type': MIME[path.extname(file)] || 'application/octet-stream' });
  fs.createReadStream(file).pipe(res);
});
await new Promise((r) => server.listen(4191, '127.0.0.1', r));
const browser = await chromium.launch({ args: ['--no-sandbox'] });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, locale: 'ko-KR' });
const page = await context.newPage();
page.on('pageerror', (e) => console.log('PAGEERROR', e.message));
page.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE', m.text()); });
await page.goto('http://127.0.0.1:4191/', { waitUntil: 'networkidle' });
for (const d of ['3', '8', '5', '5']) await page.getByLabel(`${d} 번`).click();
await page.getByText('오늘 장부').waitFor();
console.log('home ok');
const card = page.getByText('안동 풍산읍 15평 상가 원상복구 철거').first();
console.log('card count', await page.getByText('안동 풍산읍 15평 상가 원상복구 철거').count());
await card.click({ timeout: 5000 }).catch((e) => console.log('click fail', e.message.split('\n')[0]));
await page.waitForTimeout(500);
console.log('after click has tabs', await page.locator('nav[aria-label="현장 단계"]').count());
console.log('settings count', await page.getByLabel('설정').count());
await page.locator('nav[aria-label="현장 단계"] button').nth(2).click();
await page.waitForTimeout(500);
console.log('survey textarea count', await page.getByLabel('현장 변동 내용').count());
await page.getByLabel('현장 변동 내용').fill('폐기물 한 차 더 나올 듯');
await page.waitForTimeout(400);
const btn = page.locator('button[data-can-apply]').first();
console.log('apply count', await btn.count(), 'text', (await btn.innerText().catch(() => '')));
await btn.click();
await page.waitForTimeout(1200);
const main = await page.locator('main').innerText();
console.log('main head', main.split('\n').slice(0, 8).join(' / '));
console.log('settings click', await page.getByLabel('설정').first().click({ timeout: 4000 }).then(() => 'ok').catch((e) => e.message.split('\n')[0]));
await browser.close();
server.close();
