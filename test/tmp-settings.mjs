import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright';
const DIST = path.resolve('dist');
const server = http.createServer((req, res) => {
  const u = decodeURIComponent((req.url || '/').split('?')[0]);
  let f = path.join(DIST, u === '/' ? 'index.html' : u);
  if (!fs.existsSync(f) || fs.statSync(f).isDirectory()) f = path.join(DIST, 'index.html');
  res.writeHead(200, { 'Content-Type': f.endsWith('.js') ? 'text/javascript' : f.endsWith('.css') ? 'text/css' : 'text/html' });
  fs.createReadStream(f).pipe(res);
});
await new Promise((r) => server.listen(4176, '127.0.0.1', r));
const browser = await chromium.launch({ args: ['--no-sandbox'] });
const page = await (await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })).newPage();
page.setDefaultTimeout(8000);
await page.goto('http://127.0.0.1:4176/', { waitUntil: 'networkidle' });
for (const d of ['3', '8', '8', '5']) await page.getByLabel(`${d} 번`).click();
await page.getByText('오늘 장부').waitFor();
console.log('home ok');
await page.getByLabel('설정').click();
await page.getByText('우리 집 기본 단가표').waitFor();
console.log('settings ok');
await page.getByLabel('철거 기공').fill('30');
await page.getByText('우리 집 기본 단가표').scrollIntoViewIfNeeded();
await page.waitForTimeout(500);
console.log('filled ok, save count', await page.getByRole('button', { name: '저장하기' }).count());
await page.getByRole('button', { name: '저장하기' }).click();
await page.waitForTimeout(600);
console.log('saved, new btn', await page.getByRole('button', { name: /새 현장 만들기/ }).count());
await page.getByRole('button', { name: /새 현장 만들기/ }).click();
await page.waitForTimeout(500);
console.log('modal', await page.getByText('숨고·카톡·메모를 그대로 넣으세요').count());
console.log('trade count', await page.locator('div.fixed.inset-0').getByText('상가·주택 철거').count());
await page.screenshot({ path: '/workspace/.tmp/smoke/15-settings-flow.png' });
await page.locator('div.fixed.inset-0').getByText('상가·주택 철거').last().click();
await page.getByText('지금 계산된 견적').waitFor();
console.log('created', (await page.locator('main').innerText()).match(/지금 계산된 견적[\s\S]{0,40}/)?.[0]?.replace(/\n/g, ' '));
await browser.close(); server.close();
